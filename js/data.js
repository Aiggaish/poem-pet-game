// ---- 经验升级表 ----
function getExpForLevel(level) {
  return Math.floor(50 * level * level * 0.5 + 50 * level);
}

// ---- 根据等级获取宠物阶段索引 ----
function getPetStageIndex(level, petType) {
  var pet = PETS.find(function(p) { return p.id === petType; }) || PETS[0];
  var stage = 0;
  for (var i = pet.stages.length - 1; i >= 0; i--) {
    if (level >= pet.stages[i].minLevel) {
      stage = i;
      break;
    }
  }
  return stage;
}

// ---- 获取当前宠物阶段信息 ----
function getPetStageInfo(petType, level) {
  var pet = PETS.find(function(p) { return p.id === petType; }) || PETS[0];
  var idx = getPetStageIndex(level, petType);
  return pet.stages[idx];
}

// ---- 获取宠物类型信息 ----
function getPetType(petType) {
  return PETS.find(function(p) { return p.id === petType; }) || PETS[0];
}

// ---- 获取当前关卡信息 ----
function getCurrentGate(completedCount) {
  var currentGate = GATES[0];
  for (var i = GATES.length - 1; i >= 0; i--) {
    if (completedCount >= GATES[i].unlockReq) {
      currentGate = GATES[i];
      break;
    }
  }
  return currentGate;
}

// ---- 获取已解锁的最高关卡 ----
function getMaxUnlockedGate(completedCount) {
  var maxGate = 1;
  for (var i = 0; i < GATES.length; i++) {
    if (completedCount >= GATES[i].unlockReq) {
      maxGate = GATES[i].id;
    }
  }
  return maxGate;
}

// ---- 获取某关卡的古诗列表 ----
function getPoemsByGate(gateId) {
  return POEMS.filter(function(p) { return p.gate === gateId; });
}

// ---- 获取某关卡已完成数量 ----
function getGateCompletedCount(gateId, completedPoems) {
  var gatePoems = getPoemsByGate(gateId);
  return gatePoems.filter(function(p) {
    return completedPoems.indexOf(p.id) !== -1;
  }).length;
}
